TABLES = {"en": EN, "fa": FA}
_current = "en"


def resolve_language(choice: str) -> str:
    """Map a settings value (system/en/fa) to a supported language code."""
    if choice in TABLES:
        return choice
    env = os.environ.get("LC_ALL") or os.environ.get("LC_MESSAGES") or os.environ.get("LANG") or ""
    if not env:
        try:
            env = locale.getlocale()[0] or ""
        except (ValueError, TypeError):
            env = ""
    return "fa" if env.lower().startswith("fa") else "en"


def set_language(choice: str) -> str:
    global _current
    _current = resolve_language(choice)
    return _current


def current_language() -> str:
    return _current


def is_rtl() -> bool:
    return _current == "fa"


def tr(key: str, **fmt: object) -> str:
    text = TABLES.get(_current, EN).get(key) or EN.get(key) or key
    return text.format(**fmt) if fmt else text
